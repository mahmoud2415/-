# إنشاء المجلد الرئيسي إذا لم يكن موجوداً
$targetDir = Join-Path $PSScriptRoot "menu_items"
if (!(Test-Path $targetDir)) {
    New-Item -ItemType Directory -Path $targetDir | Out-Null
    Write-Host "تم إنشاء المجلد الرئيسي: $targetDir" -ForegroundColor Green
}

# إنشاء مجلد لكل صنف
foreach ($item in $items) {
    # تنظيف الاسم من أي رموز غير مسموح بها في ويندوز
    $safeName = $item -replace '[\\/:*?"<>|]', '-'
    $folderPath = Join-Path $targetDir $safeName
    
    if (!(Test-Path $folderPath)) {
        New-Item -ItemType Directory -Path $folderPath | Out-Null
        Write-Host "تم إنشاء مجلد: $safeName" -ForegroundColor Cyan
    } else {
        Write-Host "المجلد موجود بالفعل: $safeName" -ForegroundColor Yellow
    }
}

Write-Host "`nتمت العملية بنجاح! جميع المجلدات تم إنشاؤها داخل المجلد: $targetDir" -ForegroundColor Green
